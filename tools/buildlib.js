// Concatenates src/ into the CavalryAstro panel script and the in-layer runtime sources.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
// Each in-layer runtime is a list of src/core files, registered under a name by the task that adds it.
const RUNTIMES = {};
RUNTIMES.sky = ["src/core/sky.js", "src/core/stars.js", "src/core/render.js"];
RUNTIMES.reveal = ["src/core/sky.js", "src/core/reveal.js"];
const CORE_FILES = ["src/core/util.js", "src/core/update.js", "src/core/catalog.js", "src/core/sky.js", "src/core/imagery.js", "src/core/stars.js",
  "src/core/render.js", "src/core/expression.js", "src/core/styles.js", "src/core/stylefiles.js", "src/core/fly.js",
  "src/core/reveal.js", "src/core/controls.js", "src/core/preview.js"];
const CAVALRY_FILES = ["src/cavalry/attrs.js", "src/cavalry/net.js", "src/cavalry/style.js", "src/cavalry/tips.js",
  "src/cavalry/cog.js", "src/cavalry/updatecheck.js", "src/cavalry/scene.js", "src/cavalry/controls.js", "src/cavalry/preview.js", "src/cavalry/panel.js"];

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), "utf8"); }

// fs.cpSync's recursive directory copy crashes this Node build on Windows
// (STATUS_STACK_BUFFER_OVERRUN, reproduced even for a single-file source dir),
// so build.js/install.js use this manual walk instead.
function copyDirSync(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name), d = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDirSync(s, d);
    else fs.copyFileSync(s, d);
  }
}

// Copies assets/<name> into destDir, when the folder exists (the sky data arrives in a later task).
function copyAssetIfPresent(name, destDir) {
  const src = path.join(ROOT, "assets", name);
  if (fs.existsSync(src)) copyDirSync(src, path.join(destDir, name));
}

function buildRuntimeSource(name) {
  if (!Object.prototype.hasOwnProperty.call(RUNTIMES, name)) throw new Error("No runtime named " + name);
  return RUNTIMES[name].map(read).join("\n;\n");
}

// options.version overrides package.json's version (tests, and trying out the update check).
function buildPanel(options = {}) {
  const version = options.version || require(path.join(ROOT, "package.json")).version;
  return [
    "// CavalryAstro: generated by tools/build.js. Edit src/, not this file.\n" +
    "// Copyright (C) 2026 optative-visuals. Licensed under GPL-3.0-or-later; see LICENSE.\n" +
    "// Source: https://github.com/optative-visuals/CavalryAstro — this program comes with ABSOLUTELY NO WARRANTY.",
    "var ASTRO_VERSION = " + JSON.stringify(version) + ";",
    ...CORE_FILES.map(read),
    "var ASTRO_SKY_SRC = " + JSON.stringify(buildRuntimeSource("sky")) + ";",
    "var ASTRO_REVEAL_SRC = " + JSON.stringify(buildRuntimeSource("reveal")) + ";",
    ...CAVALRY_FILES.map(read)
  ].join("\n;\n");
}

module.exports = { ROOT, RUNTIMES, CORE_FILES, CAVALRY_FILES, buildRuntimeSource, buildPanel, copyDirSync, copyAssetIfPresent };
